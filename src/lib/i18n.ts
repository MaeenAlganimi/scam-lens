const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, ar, es };

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string>): string {
  const template = MESSAGES[locale][key] ?? MESSAGES.en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => params[name] ?? "");
}

export const LOCALES: readonly Locale[] = ["en", "ar", "es"];

export function isLocale(value: string | null): value is Locale {
  return value === "en" || value === "ar" || value === "es";
}
